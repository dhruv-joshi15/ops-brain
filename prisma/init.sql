CREATE TABLE IF NOT EXISTS "Task" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "data" JSONB NOT NULL
);
CREATE TABLE IF NOT EXISTS "Run" (
  "id" TEXT NOT NULL PRIMARY KEY,
  "createdAt" DATETIME NOT NULL DEFAULT CURRENT_TIMESTAMP,
  "state" TEXT NOT NULL,
  "data" JSONB NOT NULL
);
CREATE TABLE IF NOT EXISTS "RuleVersion" (
  "version" INTEGER NOT NULL PRIMARY KEY AUTOINCREMENT,
  "data" JSONB NOT NULL
);
CREATE TABLE IF NOT EXISTS "Catalog" ("id" TEXT NOT NULL PRIMARY KEY, "data" JSONB NOT NULL);
CREATE TABLE IF NOT EXISTS "AuditEvent" ("id" TEXT NOT NULL PRIMARY KEY, "data" JSONB NOT NULL);
