test("hides extraction records and clears only demo activity without duplicating or losing tasks",async({page})=>{
  const go=(name:string)=>page.getByRole("button",{name,exact:true}).click();
  const snapshot=async()=>await page.request.get("/api/ops").then(response=>response.json()) as import("../lib/contracts").Workspace;
  await page.goto("/");
  await go("Meetings");
  await go("Load synthetic sample");
  await go("Extract tasks");
  await go("Approve all valid");
  await go("Commit review");
  await expect(page.getByRole("heading",{name:"Review committed"})).toBeVisible();
  const protectedWrite=await page.request.post("/api/ops",{data:{action:"task",id:null,revision:null,fields:{
    title:"Protected activity check",description:"",owner:null,due:null,goalId:"",status:"Open",dependencies:[],priorityOverride:null,duration:null,
  }}});
  expect(protectedWrite.ok()).toBe(true);
  const initial=await snapshot();
  const committed=initial.runs.find(run=>run.state==="committed")!;
  const design=initial.tasks.find(task=>task.runId===committed.id&&task.owner==="Aditi")!;
  const response=await page.request.post("/api/ops",{data:{action:"archiveTask",id:design.id,archived:false}});
  expect(response.ok()).toBe(true);
  await go("Activity");
  await page.getByLabel(`Extraction actions for ${committed.id}`).click();
  await go("Delete record");
  await go("Confirm record removal");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  const hidden=await snapshot();
  expect(hidden.runs.some(run=>run.id===committed.id)).toBe(false);
  expect(hidden.tasks.filter(task=>task.runId===committed.id)).toHaveLength(4);
  await go("Meetings");
  await go("Load synthetic sample");
  await go("Extract tasks");
  await expect(page.getByRole("heading",{name:"Review committed"})).toBeVisible();
  expect((await snapshot()).tasks.filter(task=>task.runId===committed.id)).toHaveLength(4);
  await go("Activity");
  await page.getByRole("checkbox",{name:/Select demo log for Finalize homepage/}).check();
  await go("Clear selected demo logs");
  await go("Confirm clearing activity");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  const retained=await snapshot();
  expect(retained.events.some(event=>event.demo)).toBe(false);
  expect(retained.events.some(event=>!event.demo&&event.subject==="Protected activity check")).toBe(true);
  await go("Reset demo activity");
  await go("Confirm clearing activity");
  await expect(page.getByRole("dialog")).toHaveCount(0);
  expect((await snapshot()).tasks.filter(task=>task.runId===committed.id)).toHaveLength(4);
});
