import {expect,test} from "@playwright/test";

test("reviews and commits a meeting once, then previews its dependency impact",async({page},testInfo)=>{
  await page.setViewportSize({width:1440,height:1000});
  const errors:string[]=[];
  page.on("pageerror",error=>errors.push(error.message));
  await page.goto("/");
  await page.getByRole("button",{name:"Process meeting"}).click();
  const extract=async()=>{
    await page.getByRole("button",{name:"Load synthetic sample"}).click();
    await page.getByRole("button",{name:"Extract tasks"}).click();
  };
  await extract();
  const review=page.locator(".review-panel");
  await expect(review.getByRole("heading",{name:"Review proposed tasks"})).toBeVisible();
  const rows=review.locator(".proposal");
  await expect(rows).toHaveCount(4);
  const expected=[["Aditi","2026-11-25"],["Rahul","2026-12-05"],["Priya","2026-12-10"],["Karan","2026-12-15"]];
  for(let index=0;index<expected.length;index++){
    await rows.nth(index).locator("summary").click();
    await expect(rows.nth(index).getByLabel("Proposed owner")).toHaveValue(expected[index][0]);
    await expect(rows.nth(index).getByLabel("Due date")).toHaveValue(expected[index][1]);
    await expect(rows.nth(index).getByLabel("Goal",{exact:true})).toHaveValue("website");
    await expect(rows.nth(index).locator("input:checked")).toHaveCount(index===0?0:1);
  }
  await rows.first().getByLabel("Description").fill("Approved design scope for the launch.");
  await expect(page.getByRole("button",{name:"Commit review"})).toBeDisabled();
  await page.getByRole("button",{name:"Approve all valid"}).click();
  await page.getByLabel("Decision for task 1").selectOption("rejected");
  await page.getByRole("button",{name:"Commit review"}).click();
  await expect(page.getByRole("alert").filter({hasText:/.+/})).toContainText("dependency is missing");
  await page.getByLabel("Decision for task 1").selectOption("approved");
  await page.getByRole("button",{name:"Commit review"}).click();
  await expect(page.getByRole("heading",{name:"Review committed"})).toBeVisible();
  await extract();
  await expect(page.getByRole("heading",{name:"Review committed"})).toBeVisible();
  const headers=review.locator("summary.proposal-header");
  await expect(headers.locator(".owner-name")).toHaveText(expected.map(([owner])=>owner));
  const desktop=await headers.first().evaluate(header=>{
    const box=(selector:string)=>header.querySelector(selector)!.getBoundingClientRect();
    return {title:box(".proposal-title").left,owner:box(".owner").left,status:box(".proposal-status").left};
  });
  expect(desktop.title).toBeLessThan(desktop.owner);
  expect(desktop.owner).toBeLessThan(desktop.status);
  await review.screenshot({path:testInfo.outputPath("committed-desktop.png"),animations:"disabled"});
  await page.setViewportSize({width:390,height:844});
  await expect.poll(()=>page.evaluate(()=>document.documentElement.scrollWidth)).toBe(390);
  await expect(headers.locator(".owner-name")).toHaveText(expected.map(([owner])=>owner));
  await review.screenshot({path:testInfo.outputPath("committed-mobile.png"),animations:"disabled"});
  await page.setViewportSize({width:1440,height:1000});
  const saved=await page.request.get("/api/ops").then(response=>response.json());
  expect(saved.tasks.filter((task:{runId?:string})=>task.runId)).toHaveLength(4);
  expect(saved.runs).toHaveLength(1);
  await page.reload();
  await page.getByRole("button",{name:"Dependencies",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Dependency map"})).toBeVisible();
  await expect(page.locator(".react-flow__edge")).toHaveCount(5);
  await page.getByRole("button",{name:"Fit view",exact:true}).click();
  await expect.poll(()=>page.locator(".graph").evaluate(graph=>{
    const frame=graph.getBoundingClientRect();
    return Array.from(graph.querySelectorAll(".react-flow__node")).every(node=>{
      const box=node.getBoundingClientRect();
      return box.width>0&&box.left>=frame.left&&box.right<=frame.right&&box.top>=frame.top&&box.bottom<=frame.bottom;
    });
  })).toBe(true);
  await page.getByRole("button",{name:"Simulate delay"}).click();
  await expect(page.getByRole("heading",{name:"3 downstream tasks affected"})).toBeVisible();
  await expect(page.locator(".scenario-facts").getByText("On Track",{exact:true})).toBeVisible();
  await expect(page.locator(".scenario-facts").getByText("Off Track",{exact:true})).toBeVisible();
  await expect(page.locator(".scenario-facts").getByText("Dec 23",{exact:true})).toBeVisible();
  const drafts=page.locator(".impact-notice");
  await expect(drafts).toHaveCount(3);
  await expect(drafts.filter({hasText:"Prepare launch campaign assets"}).locator(".owner-name")).toHaveText("Karan");
  await expect(page.getByText("Slack drafts only. No messages sent.")).toBeVisible();
  await expect(page.getByText("Saved priority",{exact:false})).toHaveCount(3);
  const simulated=await page.request.get("/api/ops").then(response=>response.json());
  expect(simulated).toEqual(saved);
  await expect(page.getByText(/beyond the target/)).toBeVisible();
  await page.getByRole("button",{name:"Clear",exact:true}).click();
  await expect(page.getByRole("heading",{name:"Notification preview"})).toHaveCount(0);
  expect(errors).toEqual([]);
});

